"""Step 7.3: end-to-end latency of the Rewind API over real HTTP.

Starts the app in this process (rewind/api/app.py: config, manifest, 12 engine indexes, CLIP + LanguageBind text
encoders) behind uvicorn on 127.0.0.1, then sends GET /search requests one at a time with urllib and times each from
request to parsed JSON. Queries (20): the tuning queries' texts, then templated activity prompts ("a " + activity
name with spaces, activity types in alphabetical order) up to 20 — text only, no labels or metrics. `warmup` requests
first (not timed). Also: start-up time, the server-side split (encode / search / fuse), and a /coverage call.
Writes results/reports/api_7.3.md and one experiments row (split "none").

Run from the repo root:  uv run python -m scripts.api_latency
"""

import argparse
import json
import os
import statistics
import threading
import time
from datetime import timedelta
import urllib.parse
import urllib.request
from pathlib import Path

import numpy as np
import uvicorn
import yaml

from rewind.api.app import create_app
from rewind.eval.queries import load_queries
from rewind.experiment_log import log_experiment, run_stamp
from rewind.ingest.manifest import connect
from rewind.paths import REPO_ROOT, display_path
from scripts.run_baselines import QUERIES_DIR

N_QUERIES = 20
WARMUP = 2
PORT = 8765


def get(path: str, **params) -> tuple[dict, float]:
    url = f"http://127.0.0.1:{PORT}{path}?" + urllib.parse.urlencode({k: v for k, v in params.items() if v is not None})
    t = time.perf_counter()
    with urllib.request.urlopen(url, timeout=120) as r:
        body = json.loads(r.read())
    return body, (time.perf_counter() - t) * 1000


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--config", type=Path, default=REPO_ROOT / "configs" / "config.yaml")
    p.add_argument("--db", type=Path, default=REPO_ROOT / "data" / "rewind.sqlite")
    p.add_argument("--report", type=Path, default=REPO_ROOT / "results" / "reports" / "api_7.3.md")
    p.add_argument("--no-log", action="store_true")
    args = p.parse_args()
    stamp = run_stamp(args.config)
    cfg = yaml.safe_load(args.config.read_text())
    conn = connect(args.db)
    texts = [q["query"] for q in load_queries(QUERIES_DIR, "tuning")]
    types = sorted({r[0] for r in conn.execute("SELECT DISTINCT activity_type FROM events")})
    texts = (texts + ["a " + t.replace("_", " ") for t in types])[:N_QUERIES]

    t = time.perf_counter()
    app = create_app(args.config, args.db)
    startup_s = time.perf_counter() - t
    server = uvicorn.Server(uvicorn.Config(app, host="127.0.0.1", port=PORT, log_level="warning"))
    th = threading.Thread(target=server.run, daemon=True)
    th.start()
    while not server.started:
        time.sleep(0.05)

    for q in texts[:WARMUP]:
        get("/search", q=q)
    ms, server_ms, n_clips, examples = [], [], [], []
    for q in texts:
        body, dt = get("/search", q=q)
        ms.append(dt)
        server_ms.append(body["timing_ms"])
        n_clips.append(len(body["clips"]))
        if len(examples) < 3:
            examples.append(body)
    # one filtered request (camera + 1 h window) and /coverage, to show they work end to end
    cam = sorted(app.state.rewind.cameras)[0]
    v0 = min((v for v in app.state.rewind.videos.values() if v.camera_id == cam), key=lambda v: v.start_time)
    start = v0.start_time.isoformat()
    end = (v0.start_time + timedelta(hours=1)).isoformat()                       # the camera's first hour
    filt, filt_ms = get("/search", q=texts[0], cameras=cam, start=start, end=end)
    cov, _ = get("/coverage")
    server.should_exit = True
    th.join()

    med, p95 = statistics.median(ms), float(np.percentile(ms, 95))
    part = {k: statistics.median(s[k] for s in server_ms) for k in ("encode", "search", "fuse", "total")}
    load = os.getloadavg()
    if not args.no_log:
        log_experiment("none", {"median_ms": med, "p95_ms": p95, "max_ms": max(ms), "startup_s": startup_s,
                                **{f"server_{k}_median_ms": v for k, v in part.items()}},
                       notes=f"step 7.3 API end-to-end latency, {len(texts)} queries over HTTP, branches "
                             f"{cfg['search']['weights']}", stamp=stamp)
    w = cfg["search"]["weights"]
    lines = [
        "# Step 7.3 — API end-to-end latency", "",
        f"Generated by `scripts/api_latency.py` at git `{stamp['git_hash']}`, config `{stamp['config_hash'][:12]}`. "
        f"uvicorn on 127.0.0.1, one request at a time, timed from request to parsed JSON; {WARMUP} warm-up requests "
        f"not timed. Weights {w}; k = {cfg['search']['k_per_index']} per branch, ef_search {cfg['search']['ef_search']}; "
        f"{app.state.rewind.default_clips} clips returned. Load average during the run {load[0]:.2f} / "
        f"{load[1]:.2f} / {load[2]:.2f}.", "",
        f"- **Start-up** (config, manifest, 12 indexes, CLIP + LanguageBind on the GPU): {startup_s:.1f} s",
        f"- **End-to-end over {len(ms)} queries: median {med:.0f} ms, p95 {p95:.0f} ms**, min {min(ms):.0f}, max "
        f"{max(ms):.0f} ms",
        f"- Server side, median per part: encode {part['encode']:.1f} ms, search (all branches, 6 cameras each) "
        f"{part['search']:.1f} ms, fusion + clips {part['fuse']:.1f} ms, total {part['total']:.1f} ms",
        f"- Clips per response: {min(n_clips)}–{max(n_clips)}",
        f"- Filtered request (camera {cam}, {start} to {end}): {filt_ms:.0f} ms, {len(filt['clips'])} clips, methods "
        f"{filt['methods']}; coverage line: \"{filt['coverage']['line']}\"",
        f"- /coverage (everything): \"{cov['line']}\"", "",
        "## Per query", "", "| # | query | ms | server ms (encode / search / fuse) | clips |", "|---|---|---|---|---|",
        *(f"| {i + 1} | {q} | {m:.0f} | {s['encode']:.0f} / {s['search']:.0f} / {s['fuse']:.0f} | {n} |"
          for i, (q, m, s, n) in enumerate(zip(texts, ms, server_ms, n_clips))), "",
        "## Example response (first query, top 3 clips)", "", "```json",
        json.dumps({**examples[0], "clips": examples[0]["clips"][:3]}, indent=1), "```", ""]
    args.report.write_text("\n".join(lines))
    print("\n".join(lines[:12]))
    print("report:", display_path(args.report))


if __name__ == "__main__":
    main()
